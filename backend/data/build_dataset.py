def generate_user_interactions(destinations, num_users=350, min_ratings=6, max_ratings=15):
    random.seed(42)
    np.random.seed(42)

    ratings = []
    persona_preferences = {
        0: ["Beaches", "Adventure"],
        1: ["Adventure", "Nature/Hiking", "Waterfalls"],
        2: ["Heritage/Cultural", "Scenic/Tea Country"],
        3: ["Wildlife/Safari", "Nature/Hiking"],
        4: ["Scenic/Tea Country", "Waterfalls", "Nature/Hiking"]
    }

    rating_id = 1
    for user_id in range(1, num_users + 1):
        persona = random.randint(0, 4)
        fav_categories = persona_preferences[persona]
        num_rated = random.randint(min_ratings, max_ratings)
        
        weights = []
        for d in destinations:
            if d["category"] in fav_categories:
                weights.append(3.5)
            else:
                weights.append(0.8)
        
        weights = np.array(weights) / sum(weights)
        chosen_dest_indices = np.random.choice(len(destinations), size=num_rated, replace=False, p=weights)

        for idx in chosen_dest_indices:
            dest = destinations[idx]
            if dest["category"] in fav_categories:
                rating_score = round(random.choices([4.0, 4.5, 5.0], weights=[0.2, 0.4, 0.4])[0], 1)
            else:
                rating_score = round(random.choices([2.0, 3.0, 3.5, 4.0], weights=[0.15, 0.35, 0.3, 0.2])[0], 1)
            
            ratings.append({
                "rating_id": rating_id,
                "user_id": user_id,
                "destination_id": dest["id"],
                "rating": rating_score,
                "user_persona": persona
            })
            rating_id += 1

    return pd.DataFrame(ratings)


def build_and_save():
    os.makedirs("backend/data", exist_ok=True)
    
    # 1. Save destinations.csv
    df_dest = pd.DataFrame(DESTINATIONS)
    dest_path = "backend/data/destinations.csv"
    df_dest.to_csv(dest_path, index=False)
    print(f"[OK] Saved {len(df_dest)} curated destinations to {dest_path}")

    # 2. Generate and save user_ratings.csv
    df_ratings = generate_user_interactions(DESTINATIONS, num_users=350)
    ratings_path = "backend/data/user_ratings.csv"
    df_ratings.to_csv(ratings_path, index=False)
    print(f"[OK] Saved {len(df_ratings)} synthetic user interaction ratings to {ratings_path}")

if __name__ == "__main__":
    build_and_save()
